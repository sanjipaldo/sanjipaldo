-- 027: 관리자 요청(2026-10-27)으로 '미분류' 카테고리 이름을 '📦 기타'로 바꾸고 카테고리 목록 맨 뒤(해외 건강식품 다음)로 보냅니다.
-- - 카테고리 이름·순서만 바꾸며, 상품의 카테고리·가격·노출 등 상품 값은 바꾸지 않습니다.
-- - 국내·해외 '미분류'가 둘 다 있으면 둘 다 '📦 기타'가 되고, 공개 단가표 '전체' 보기에서는 버튼 하나로 합쳐 보여 줍니다.
-- - 여러 번 실행돼도 같은 결과입니다.
UPDATE categories
SET name = '📦 기타', sortOrder = 99999, updatedAt = CURRENT_TIMESTAMP
WHERE name = '미분류';
